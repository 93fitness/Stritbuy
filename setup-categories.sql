-- StritBuy: categories you can change WITHOUT touching the website code.
-- Run this ONCE in Supabase > SQL Editor (StritBuy project). Safe to run again: it never overwrites your edits.
--
-- After that, manage categories in Supabase > Table Editor > categories:
--   REMOVE  a category: set active to false (or delete the row)
--   ADD     a category: Insert row, fill name, emoji and sort, leave active true
--   REORDER: change the sort number (smaller numbers appear first)
--   RENAME: change the name. Shops already using the old name keep it, so prefer add + remove.
-- Changes show on the website after a refresh. No upload to GitHub is needed.

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  emoji text not null default '🛍️',
  sort int not null default 100,
  active boolean not null default true
);
alter table public.categories enable row level security;
drop policy if exists "categories: anyone can read" on public.categories;
create policy "categories: anyone can read" on public.categories for select using (true);
grant select on public.categories to anon, authenticated;

